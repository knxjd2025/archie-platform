function materialRow(item: string, qty: number, unit: string): string {
  // Defensive: NaN propagates through `%` and would render "NaN" in
  // customer-facing reports. Treat junk as 0.
  const safeQty = Number.isFinite(qty) ? qty : 0;
  // Show one decimal for fractional quantities, integer otherwise.
  const qtyStr = safeQty % 1 !== 0 ? safeQty.toFixed(1) : String(safeQty);
  return `      <tr>
        <td>${escapeHtml(item)}</td>
        <td class="num">${qtyStr}</td>
        <td>${escapeHtml(unit)}</td>
      </tr>`;
}

function buildCostSection(costs: MaterialCostLine[], brandColor: string): string {
  const total = costs.reduce((sum, c) => sum + c.qty * c.unitPrice, 0);

  return `
<!-- Material Cost Estimate -->
<div class="section" data-reveal>
  <div class="section-title">${LABEL_MATERIAL_COST_HEADING}</div>
  <table>
    <thead>
      <tr>
        <th>${COST_TABLE_COLS.item}</th>
        <th class="num">${COST_TABLE_COLS.qty}</th>
        <th>${COST_TABLE_COLS.unit}</th>
        <th class="num">${COST_TABLE_COLS.unitPrice}</th>
        <th class="num">${COST_TABLE_COLS.subtotal}</th>
      </tr>
    </thead>
    <tbody>
${costs.map(c => {
  const unitPrice = Number.isFinite(c.unitPrice) ? c.unitPrice : 0;
  const subtotal = Number.isFinite(c.qty) ? c.qty * unitPrice : 0;
  return `      <tr>
        <td>${escapeHtml(c.label)}</td>
        <td class="num">${c.qty}</td>
        <td>${escapeHtml(c.unit)}</td>
        <td class="num">${USD_FORMATTER.format(unitPrice)}</td>
        <td class="num">${USD_FORMATTER.format(subtotal)}</td>
      </tr>`;
}).join('\n')}
      <tr class="total-row">
        <td colspan="4">${LABEL_TOTAL_ESTIMATED_COST}</td>
        <td class="num" style="font-size:14px;">${USD_FORMATTER.format(Number.isFinite(total) ? total : 0)}</td>
      </tr>
    </tbody>
  </table>
  <div style="font-size:10px;color:#9ca3af;margin-top:6px;">
    ${MSG_COST_DISCLAIMER}
  </div>
</div>
`;
}

function buildEdgeLengthsSection(edges: RoofEdgeLengths): string {
  const rows = EDGE_LABEL_DEFINITIONS.map((def) => ({
    label: def.label,
    value: edges[def.key] as number,
  }));

  const total = rows.reduce((s, r) => s + r.value, 0);
  const maxEdge = rows.reduce((mx, r) => (r.value > mx ? r.value : mx), 0);

  return `
<!-- Edge Lengths -->
<div class="section" data-reveal>
  <div class="section-title">${LABEL_EDGE_LENGTHS_HEADING_INTERNAL}</div>
  <table>
    <thead>
      <tr>
        <th>${EDGE_LENGTHS_COLS.edgeType}</th>
        <th class="num">${EDGE_LENGTHS_COLS.lengthFt}</th>
      </tr>
    </thead>
    <tbody>
${rows.map(r => {
  const barPct = maxEdge > 0 && r.value > 0 ? Math.round((r.value / maxEdge) * 100) : 0;
  const valCell = r.value > 0
    ? `<div class="mbar-cell"><span class="mbar-track"><span class="mbar-fill" data-bar-fill style="width:${barPct}%"></span></span><span class="mbar-num">${r.value.toFixed(EDGE_LENGTH_DECIMALS)}</span></div>`
    : EMPTY_EDGE_PLACEHOLDER;
  return `      <tr>
        <td>${escapeHtml(r.label)}</td>
        <td class="num">${valCell}</td>
      </tr>`;
}).join('\n')}
      <tr class="total-row">
        <td>${LABEL_TOTAL_PLAIN}</td>
        <td class="num">${total.toFixed(EDGE_LENGTH_DECIMALS)}</td>
      </tr>
    </tbody>
  </table>
</div>
`;
}
