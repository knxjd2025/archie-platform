/**
 * Generate the report HTML, open it in a new window, and trigger the print
 * dialog. Returns `true` on success and `false` if the popup was blocked
 * — callers can then surface a toast pointing the user at popup settings.
 */
export function openPrintReport(data: ReportData): boolean {
  const html = generateReportHtml(data);
  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    console.error(MSG_POPUP_BLOCKED);
    return false;
  }
  printWindow.document.write(html);
  printWindow.document.close();

  printWindow.onload = async () => {
    try {
      await printWindow.document.fonts.ready;
    } catch {
      await new Promise(r => setTimeout(r, FONT_LOAD_FALLBACK_MS));
    }
    printWindow.focus();
    printWindow.print();
  };

  return true;
}

